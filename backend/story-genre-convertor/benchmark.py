"""Run the whole corpus through the pipeline and write METRICS.md.

Every story in stories/corpus/ is assigned a genre by a seeded shuffle — random,
but reproducible, so re-running produces the same pairing rather than a new one
to explain. Each genre is used at least twice.

    python benchmark.py                 # resume from .cache/
    python benchmark.py --no-cache      # recompute everything
    python benchmark.py --limit 3       # first 3 pairings only, for a smoke test

Everything is cached, so an interrupted run resumes where it stopped.
"""

import argparse
import random
import statistics
import sys
import time
from pathlib import Path
from typing import Dict, List

from genre_pack import available_packs
from models import StorySkeleton
from pipeline import convert

CORPUS = Path(__file__).parent / "stories" / "corpus"
CACHE = Path(__file__).parent / ".cache"
OUT = Path(__file__).parent / "METRICS.md"

# Fixed so the pairing is reproducible. Change it to reshuffle.
SEED = 20260725


def assign_genres(stories: List[Path], genres: List[str]) -> List[tuple]:
    """Pair each story with a genre, using every genre at least twice."""
    rng = random.Random(SEED)
    pool: List[str] = []
    while len(pool) < len(stories):
        block = list(genres)
        rng.shuffle(block)
        pool.extend(block)
    pool = pool[: len(stories)]
    order = list(stories)
    rng.shuffle(order)
    return list(zip(order, pool))


def _excerpt(text: str, words: int = 45) -> str:
    parts = text.split()
    return " ".join(parts[:words]) + ("…" if len(parts) > words else "")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--no-cache", action="store_true")
    parser.add_argument("--limit", type=int, default=0)
    args = parser.parse_args()

    stories = sorted(CORPUS.glob("*.txt"))
    if not stories:
        print(f"no stories in {CORPUS}", file=sys.stderr)
        return 2

    pairs = assign_genres(stories, available_packs())
    if args.limit:
        pairs = pairs[: args.limit]

    started = time.time()
    rows: List[Dict[str, object]] = []

    for index, (path, genre) in enumerate(pairs, 1):
        print("=" * 68, file=sys.stderr)
        print(f"[{index}/{len(pairs)}] {path.stem} -> {genre}", file=sys.stderr)
        print("=" * 68, file=sys.stderr)
        try:
            result = convert(path, genre, use_cache=not args.no_cache)
        except Exception as exc:  # a single failure must not lose the whole run
            print(f"  FAILED: {exc}", file=sys.stderr)
            rows.append({"story": path.stem, "genre": genre, "failed": str(exc)})
            continue
        result["source_words"] = len(path.read_text().split())
        rows.append(result)
        print(f"  fidelity {result['fidelity']:.2%}", file=sys.stderr)

    write_report(rows, round(time.time() - started, 1))
    print(f"\nwrote {OUT}", file=sys.stderr)
    return 0


def write_report(rows: List[Dict[str, object]], elapsed: float) -> None:
    ok = [r for r in rows if "failed" not in r]
    fid = [r["fidelity"] for r in ok]

    lines: List[str] = []
    add = lines.append

    add("# Corpus benchmark")
    add("")
    add(
        f"{len(rows)} stories written for this run, each converted to one randomly "
        f"assigned genre and scored for plot fidelity. Pairing is a seeded shuffle "
        f"(seed `{SEED}`), so re-running reproduces it."
    )
    add("")
    add(f"Generated by `benchmark.py` in {elapsed / 60:.1f} minutes.")
    add("")

    # ---- headline ----
    add("## Results")
    add("")
    if fid:
        add(f"- **Mean fidelity: {statistics.mean(fid):.2%}**")
        add(f"- Median: {statistics.median(fid):.2%}")
        add(f"- Range: {min(fid):.2%} – {max(fid):.2%}")
        if len(fid) > 1:
            add(f"- Standard deviation: {statistics.stdev(fid):.2%}")
    failed = [r for r in rows if "failed" in r]
    if failed:
        add(f"- **{len(failed)} run(s) failed:** {', '.join(r['story'] for r in failed)}")
    add("")

    # ---- per conversion ----
    add("### Per conversion")
    add("")
    add("| Story | Genre | Fidelity | Load-bearing | All beats | Edges | In | Out | Time |")
    add("|---|---|---:|---:|---:|---:|---:|---:|---:|")
    for r in sorted(ok, key=lambda x: -x["fidelity"]):
        add(
            f"| `{r['story']}` | {r['genre']} | **{r['fidelity']:.1%}** | "
            f"{r['load_bearing_recall_counts']} | {r['beat_recall_counts']} | "
            f"{r['edge_recall_counts']} | {r['source_words']}w | {r['words']}w | "
            f"{r['seconds']:.0f}s |"
        )
    for r in failed:
        add(f"| `{r['story']}` | {r['genre']} | — | — | — | — | — | — | failed |")
    add("")

    # ---- per genre ----
    add("### By genre")
    add("")
    add("| Genre | Runs | Mean fidelity | Mean length |")
    add("|---|---:|---:|---:|")
    for genre in available_packs():
        got = [r for r in ok if r["genre"] == genre]
        if not got:
            add(f"| {genre} | 0 | — | — |")
            continue
        add(
            f"| {genre} | {len(got)} | {statistics.mean(g['fidelity'] for g in got):.1%} | "
            f"{statistics.mean(g['words'] for g in got):.0f}w |"
        )
    add("")
    add(
        "> Genre differences here are **not** significant. The alignment judge was "
        "measured swinging 25 points on identical input before majority voting was "
        "added, and these samples are 2–3 runs each. Read the column as a sanity "
        "check that no genre collapses, not as a ranking."
    )
    add("")

    # ---- dropped beats ----
    add("### What got lost")
    add("")
    any_loss = False
    for r in sorted(ok, key=lambda x: x["story"]):
        missing = r.get("missing_load_bearing") or []
        broken = r.get("broken_edges") or []
        if not missing and not broken:
            continue
        any_loss = True
        bits = []
        if missing:
            bits.append(f"dropped load-bearing: `{', '.join(missing)}`")
        if broken:
            bits.append(f"broken edges: `{', '.join(broken)}`")
        add(f"- **{r['story']} → {r['genre']}** — {'; '.join(bits)}")
    if not any_loss:
        add("Nothing dropped in any run.")
    add("")

    # ---- the stories ----
    add("## The stories")
    add("")
    add("Written for this benchmark, in `stories/corpus/`. Deliberately different")
    add("plot shapes — a shared shape across the corpus would make the floor check")
    add("meaningless.")
    add("")
    add("| Story | Words | Beats | Load-bearing | Edges | Opens |")
    add("|---|---:|---:|---:|---:|---|")
    for r in sorted(ok, key=lambda x: x["story"]):
        skel_path = CACHE / f"{r['story']}.json"
        beats = lb = edges = "—"
        if skel_path.exists():
            sk = StorySkeleton.model_validate_json(skel_path.read_text())
            beats, lb, edges = len(sk.beats), len(sk.load_bearing_ids), len(sk.causal_edges)
        opening = _excerpt((CORPUS / f"{r['story']}.txt").read_text(), 14)
        add(f"| `{r['story']}` | {r['source_words']} | {beats} | {lb} | {edges} | {opening} |")
    add("")

    # ---- rewrites ----
    add("## The rewrites")
    add("")
    add("First lines of each conversion. Full text in `.cache/<story>__<genre>.txt`.")
    add("")
    for r in sorted(ok, key=lambda x: x["story"]):
        text_path = CACHE / f"{r['story']}__{r['genre']}.txt"
        if not text_path.exists():
            continue
        add(f"**`{r['story']}` as {r['genre']}** — fidelity {r['fidelity']:.1%}")
        add("")
        add(f"> {_excerpt(text_path.read_text(), 55)}")
        add("")

    # ---- caveats ----
    add("## How to read these numbers")
    add("")
    add(
        "Fidelity is 60% load-bearing beat recall, 20% all-beat recall, 20% causal "
        "edge recall, computed in plain Python from a majority vote of three "
        "independent alignment calls. See [ARCHITECTURE.md](ARCHITECTURE.md)."
    )
    add("")
    add("Three things this benchmark does **not** establish:")
    add("")
    add(
        "1. **A trustworthy upper bound.** `calibrate.py` reports a 100% ceiling, but "
        "the two passes it compares came out byte-identical — at temperature 0 with "
        "the same prompt, that measures API determinism, not extractor robustness. "
        "The real ceiling needs a perturbed second pass and is still unknown."
    )
    add(
        "2. **That genre A beats genre B.** Sample sizes are 2–3 and the judge has "
        "demonstrated instrument noise larger than the gaps between genres."
    )
    add(
        "3. **That a dropped beat is real.** Some are alignment artifacts. Every "
        "loss listed above is worth reading by hand before believing it — in an "
        "earlier run, one of two reported drops turned out to be present in the "
        "prose and mis-scored."
    )
    add("")
    add(
        "What it does establish: the pipeline runs end to end across a varied corpus "
        "without failing, no genre collapses, and the load-bearing spine survives in "
        "the large majority of runs."
    )
    add("")

    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    raise SystemExit(main())
